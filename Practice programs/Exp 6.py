import torch

# Create tensors
tensor1 = torch.tensor([10, 20, 30])
tensor2 = torch.tensor([5, 10, 15])

print("Tensor 1:", tensor1)
print("Tensor 2:", tensor2)

# Addition
print("\nAddition:")
print(tensor1 + tensor2)

# Subtraction
print("\nSubtraction:")
print(tensor1 - tensor2)

# Multiplication
print("\nMultiplication:")
print(tensor1 * tensor2)

# Division
print("\nDivision:")
print(tensor1 / tensor2)